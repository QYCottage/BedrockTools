IconPixels makeEffectIcon(std::uint32_t id, std::uint32_t color) {
    IconPixels pixels{};
    const std::uint32_t rim = ((color & 0xFEFEFE) >> 1);
    const std::uint32_t shade = ((color & 0xFCFCFC) >> 2);

    // Pixel-art medallion: a colored disc with a darker rim so the glyph
    // stays readable on any HUD background.
    for (int y = 1; y < 15; ++y) {
        for (int x = 1; x < 15; ++x) {
            const int dx = x - 7;
            const int dy = y - 7;
            const int distance = dx * dx + dy * dy;
            if (distance <= 43) setPixel(pixels, x, y, distance >= 32 ? rim : color);
        }
    }

    if (id < kGlyphs.size()) {
        const auto& glyph = kGlyphs[id];
        for (int y = 0; y < kIconSize; ++y) {
            for (int x = 0; x < kIconSize; ++x) {
                const char value = glyph[static_cast<std::size_t>(y)][static_cast<std::size_t>(x)];
                if (value == '1') setPixel(pixels, x, y, 0xFFF7D6);
                else if (value == '2') setPixel(pixels, x, y, shade);
            }
        }
    }

    return pixels;
}

